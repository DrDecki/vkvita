#!/usr/bin/env python3
# Turns docs/vkvita-logo.png into src/vkv_splash_logo.h, a run-length encoded
# coverage mask that the boot screen draws in the logo color.
# Usage: python3 tools/gen_splash_logo.py [width]
import os, sys
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
width = int(sys.argv[1]) if len(sys.argv) > 1 else 520
im = Image.open(os.path.join(root, "docs", "vkvita-logo.png")).convert("RGBA")
height = round(im.height * width / im.width)
# the source has faint alpha noise around the logo, cut it off before scaling
mask = im.getchannel("A").point(lambda a: 0 if a < 16 else min(255, (a - 16) * 255 // 239))
mask = mask.resize((width, height), Image.LANCZOS)
r, g, b = im.convert("RGB").getpixel((im.width // 2, im.height // 2))
for x in range(im.width):
    if im.getpixel((x, im.height // 2))[3] == 255:
        r, g, b = im.getpixel((x, im.height // 2))[:3]
        break

runs = []
data = mask.tobytes()
i = 0
while i < len(data):
    v = data[i]
    n = 1
    while i + n < len(data) and data[i + n] == v and n < 255:
        n += 1
    runs += [n, v]
    i += n

out = ["/* Generated by tools/gen_splash_logo.py from docs/vkvita-logo.png. Do not edit. */",
       "#define VKV_SPLASH_LOGO_W %d" % width,
       "#define VKV_SPLASH_LOGO_H %d" % height,
       "#define VKV_SPLASH_LOGO_COLOR 0x%02X%02X%02Xu /* B G R */" % (b, g, r),
       "static const unsigned char k_splashLogoRle[%d] = {" % len(runs)]
for k in range(0, len(runs), 24):
    out.append("\t" + ",".join(str(x) for x in runs[k:k + 24]) + ",")
out.append("};")
with open(os.path.join(root, "src", "vkv_splash_logo.h"), "w") as f:
    f.write("\n".join(out) + "\n")
print("%dx%d, %d bytes, color %d,%d,%d" % (width, height, len(runs), r, g, b))
