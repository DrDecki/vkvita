#!/usr/bin/env python3
"""Regenerates src/vkv_dispatch.c from the vk* functions implemented in src/*.c.
Run from the repo root: python3 tools/gen_dispatch.py"""
import re, glob, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
names = set()
for path in sorted(glob.glob(os.path.join(root, "src", "*.c"))):
    if path.endswith("vkv_dispatch.c"):
        continue
    src = open(path).read()
    names.update(re.findall(r"VKAPI_ATTR\s+[\w\s\*]+?VKAPI_CALL\s+(vk\w+)\s*\(", src))

# extension aliases that share an implementation
aliases = {
    "vkGetPhysicalDeviceProperties2KHR": "vkGetPhysicalDeviceProperties2",
    "vkGetPhysicalDeviceFeatures2KHR": "vkGetPhysicalDeviceFeatures2",
    "vkGetPhysicalDeviceMemoryProperties2KHR": "vkGetPhysicalDeviceMemoryProperties2",
}
entries = sorted([(n, n) for n in names] + [(a, t) for a, t in aliases.items() if t in names])

out = ["/* Generated by tools/gen_dispatch.py - do not edit. */",
       '#include "vkv_internal.h"', "",
       "typedef struct { const char *name; PFN_vkVoidFunction fn; } VkvProc;", "",
       "static const VkvProc k_procs[] = {"]
for name, target in entries:
    out.append('\t{ "%s", (PFN_vkVoidFunction)%s },' % (name, target))
out += ["};", "",
        "PFN_vkVoidFunction vkv_lookup_proc(const char *name) {",
        "\tif (!name) return NULL;",
        "\tsize_t lo = 0, hi = sizeof(k_procs) / sizeof(k_procs[0]);",
        "\twhile (lo < hi) {",
        "\t\tsize_t mid = (lo + hi) / 2;",
        "\t\tint c = strcmp(name, k_procs[mid].name);",
        "\t\tif (!c) return k_procs[mid].fn;",
        "\t\tif (c < 0) hi = mid; else lo = mid + 1;",
        "\t}",
        "\treturn NULL;",
        "}", ""]
open(os.path.join(root, "src", "vkv_dispatch.c"), "w").write("\n".join(out))
print("%d entry points" % len(entries))
