#!/usr/bin/env python3
# Rasterizes DejaVu Sans Mono into the 8x16 one-bit font of the boot screen
# text helper (vkvSplashText) and writes src/vkv_splash_font.h.
# Needs Pillow and the DejaVu fonts. Run from the repository root.
import os
from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
W, H = 8, 16

font = ImageFont.truetype(FONT, 13)
rows = []
for c in range(32, 127):
    img = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    d.text((0, -1), chr(c), font=font, fill=255)
    px = img.load()
    for y in range(H):
        bits = 0
        for x in range(W):
            if px[x, y]:
                bits |= 0x80 >> x
        rows.append(bits)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ["/* Generated by tools/gen_splash_font.py from DejaVu Sans Mono. Do not edit. */",
       "/* 8x16 glyphs for ASCII 32 to 126, one byte per row, top bit is the left pixel. */",
       "static const unsigned char k_splashFont[95 * 16] = {"]
for i in range(0, len(rows), 16):
    out.append("\t" + ",".join("0x%02x" % b for b in rows[i:i + 16]) + ",  /* %r */" % chr(32 + i // 16))
out.append("};")
open(os.path.join(root, "src", "vkv_splash_font.h"), "w").write("\n".join(out).replace("/* '*' */", "/* star */") + "\n")
print("wrote src/vkv_splash_font.h")
